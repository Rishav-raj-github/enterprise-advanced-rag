# Fallback LLM Simulator for offline / API key-less executions
class MockLLMClient:
    """
    A highly intelligent Mock LLM Client that parses retrieved contexts
    and synthesizes dynamic responses to simulate a real generative model.
    """
    def __init__(self):
        print("[LLM Interface] Initializing MockLLMClient fallback (No active API keys found).")

    def generate_content(self, prompt: str) -> str:
        prompt_lower = prompt.lower()
        
        # 1. Text-to-SQL Node Simulator
        if "sql" in prompt_lower and "schema" in prompt_lower:
            if "sales" in prompt_lower or "revenue" in prompt_lower:
                return "SELECT SUM(total_amount) FROM sales;"
            elif "products" in prompt_lower:
                return "SELECT name, price FROM products ORDER BY price DESC LIMIT 5;"
            return "SELECT * FROM sqlite_master WHERE type='table';"
            
        # 2. Safety / Guardrail Simulator
        if "ignore previous instructions" in prompt_lower or "jailbreak" in prompt_lower:
            return "SAFETY_TRIGGERED: Prompt violates system security guidelines."
            
        # 3. Document Relevance Grader
        if "grade" in prompt_lower or "relevant" in prompt_lower:
            if "hr" in prompt_lower or "leave" in prompt_lower or "hybrid" in prompt_lower:
                return "CORRECT"
            if "server" in prompt_lower or "gateway" in prompt_lower or "redis" in prompt_lower:
                return "CORRECT"
            if "mfa" in prompt_lower or "encryption" in prompt_lower or "kms" in prompt_lower:
                return "CORRECT"
            return "INCORRECT"
            
        # 4. Self-RAG Grader
        if "hallucination" in prompt_lower:
            return "FAITHFUL"
        if "utility" in prompt_lower:
            return "HIGHLY_USEFUL"
            
        # 5. General Q&A (Acme HR manual)
        if "stipend" in prompt_lower or "remote" in prompt_lower:
            return "Based on Acme Corp's HR Policy Manual (SEC-1), fully remote employees receive a $1,500 setup stipend, and hybrid employees receive $750. Commuters get up to $200/month."
            
        # 6. General Q&A (Acme Systems Architecture)
        if "gateway" in prompt_lower or "kong" in prompt_lower:
            return "According to Acme systems specification (ARCH-SPEC), Kong API Gateway acts as ingress controlling JWT Auth, TLS 1.3 encryption, and rate-limiting (Basic: 60/min, Enterprise: 10,000/min)."
            
        # 7. General Q&A (Acme Cloud Security)
        if "mfa" in prompt_lower or "auth" in prompt_lower:
            return "As documented in the Security Guide (SEC-GUIDE), Multi-Factor Authentication (MFA) is strictly mandatory using hardware keys (YubiKeys) or auth apps. SMS-based MFA is banned."
            
        return "This is a structured response generated by the Enterprise Advanced RAG simulation platform. Please configure a valid GOOGLE_API_KEY in your .env file to enable live Gemini generative predictions."

def get_llm():
    """
    Returns an active Gemini model client if API key is provided, 
    otherwise returns the highly resilient MockLLMClient.
    """
    if GOOGLE_API_KEY:
        try:
            import google.generativeai as genai
            genai.configure(api_key=GOOGLE_API_KEY)
            # Use Gemini 1.5 Flash for high performance and low latency
            model = genai.GenerativeModel('gemini-1.5-flash')
            # Wrap to share a common generate_content interface
            class GeminiWrapper:
                def __init__(self, m):
                    self.m = m
                def generate_content(self, prompt: str) -> str:
                    try:
                        response = self.m.generate_content(prompt)
                        return response.text
                    except Exception as e:
                        print(f"[LLM Error] Gemini call failed: {e}. Falling back to MockLLM.")
                        return MockLLMClient().generate_content(prompt)
            return GeminiWrapper(model)
        except Exception as e:
            print(f"[LLM Setup Error] Could not initialize Gemini: {e}")
            return MockLLMClient()
    else:
        return MockLLMClient()
